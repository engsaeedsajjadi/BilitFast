/** گلیف به‌صورت آرایهٔ سطرها؛ هر سطر آرایهٔ ۰/۱ (۵ ستون). */
function glyphRows(ch, font = 'plain') {
  const rows = RAW[ch];
  if (!rows) throw new Error('گلیف تعریف‌نشده: ' + ch);
  let grid = rows.map((r) => [4, 3, 2, 1, 0].map((bit) => (r >> bit) & 1));
  if (font === 'bold') {
    // ضخیم‌کردن: گسترش افقی هر پیکسل جوهر
    grid = grid.map((row, y) => row.map((v, x) => {
      if (v) return 1;
      return (x > 0 && rows[y] & (1 << (5 - x))) ? 1 : 0;
    }));
    grid = grid.map((row, y) => row.map((v, x) => {
      if (v) return 1;
      const up = y > 0 && (rows[y - 1] >> (4 - x)) & 1;
      return up ? 1 : 0;
    }));
  } else if (font === 'serif') {
    // پایه‌دار: افزودن پیکسل در دو انتهای ستون‌های عمودیِ متصل به لبهٔ پایین
    grid = grid.map((r) => r.slice());
    for (let x = 0; x < 5; x++) {
      if (grid[6][x]) {
        if (x > 0) grid[6][x - 1] = grid[6][x - 1] || grid[5][x] ? grid[6][x - 1] : 0;
      }
    }
    grid[6] = grid[6].map((v, x) => (x === 0 || x === 4 ? v : v));
    grid[0] = grid[0].map((v, x) => v);
    // خطوط پایه در پایین گلیف‌های بلند
    if (grid[6].reduce((a, b) => a + b, 0) >= 2) {
      grid[6] = grid[6].map((v, x) => (v || (x > 0 && grid[6][x - 1]) || (x < 4 && grid[6][x + 1])) ? 1 : v);
    }
  }
  return grid;
}

