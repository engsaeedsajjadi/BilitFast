'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
let assertions = 0;
function check(name, fn) {fn(); assertions++; console.log('PASS: '+name);}
const {validate, OFFICIAL} = require('../extension/official-handoff');
const input = { url:OFFICIAL,method:'POST',fields:{from:'1',to:'191',pathWay:'1',srvc:'train-token',passCnt:'1'}};
check('only official HTTPS POST URL allowed',()=>assert.equal(validate(input).url, OFFICIAL));
check('fields are normalized as strings',()=>assert.equal(validate({...input,fields:{...input.fields,from:1}}).fields.from, '1'));
check('invalid origin rejected',()=>assert.throws(()=>validate({...input,url:'https://evil.test/TresV-auth.php'})));
check('http downgrade rejected',()=>assert.throws(()=>validate({...input,url:'http://safirrail.ir/etrain/TresV-auth.php'})));
check('no service identifier rejected',()=>assert.throws(()=>validate({...input,fields:{from:'1'}})));
check('unknown form field rejected',()=>assert.throws(()=>validate({...input,fields:{...input.fields,arcaptcha_token:'forged'}})));
check('CRLF field content rejected',()=>assert.throws(()=>validate({...input,fields:{...input.fields,from:'1\r\nInjected:yes'}})));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'extension/manifest.json')));
check('the real Safir site content script is first party',()=>assert.deepEqual(manifest.content_scripts[0].matches,['https://safirrail.ir/etrain/*']));
check('no Electron dependency in shipped web manifest',()=>assert.equal(manifest.manifest_version,3));
const page=fs.readFileSync(path.join(root,'public/route.html'),'utf8');
check('web route publishes explicit handoff',()=>assert(page.includes("$('bf-browser-handoff').textContent = valid ? JSON.stringify(payload) : ''")));
check('route no longer invokes desktop ARCaptcha bridge',()=>assert(!page.includes('openSafirHumanChallenge')));
const popup=fs.readFileSync(path.join(root,'extension/popup.js'),'utf8');
const bg=fs.readFileSync(path.join(root,'extension/background.js'),'utf8');
check('official first-party POST queued for the same-tab worker',()=>assert(popup.includes("bilitOneTabHandoff") && bg.includes("form.method='POST'")));
check('extension prevents different profile transfer',()=>assert(popup.includes('sourceStore.id !== destinationStore.id')));
check('extension stores short-lived passenger data',()=>assert(popup.includes('bilitPendingPassengerFill')));
check('passenger info only released to official origin',()=>assert(bg.includes('safirrail\\.ir\\/etrain')));
check('passenger info expires',()=>assert(bg.includes('15*60*1000')));
const helper=fs.readFileSync(path.join(root,'extension/safir-passenger-helper.js'),'utf8');
check('passenger fill requires click',()=>assert(helper.includes("button.addEventListener('click'") && !helper.includes('void fillFromExtension();return;')));
check('helper does not simulate captcha click, forge token or submit payment',()=>assert(!/\.click\(\)|form\.submit\(|arcaptcha-token[^\n]*\.value\s*=/.test(helper)));
check('user reviews before submitting on official page',()=>assert(helper.includes('قطار و مبلغ را بررسی')));
console.log('ALL '+assertions+' official-browser-handoff assertions passed');
