// Real persistent-record behavior; host identities injected via temp files.
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(),'bf-machine-binding-'));
const before = { ...process.env };
try {
  const sourceA = path.join(tmp,'machine-A');
  const sourceB = path.join(tmp,'machine-B');
  fs.writeFileSync(sourceA,'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa');
  fs.writeFileSync(sourceB,'bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb');
  process.env.BILITFAST_SELF_HOSTED = '1';
  process.env.BILITFAST_DATA_DIR = path.join(tmp,'new');
  process.env.BILITFAST_HOST_MACHINE_ID_FILE = sourceA;
  const license = require('../lib/selfhost-license');
  const record = license.initial();
  assert.equal(record.v,2);
  assert.match(record.machineHash,/^[a-f0-9]{64}$/);
  assert(!fs.readFileSync(license.filePath(),'utf8').includes('aaaa'));
  assert.equal(license.status().state,'active');
  process.env.BILITFAST_HOST_MACHINE_ID_FILE = sourceB;
  assert.throws(()=>license.initial(),/سیستم دیگری/);
  assert.throws(()=>license.status(),/سیستم دیگری/);
  assert.throws(()=>license.redeem('BF1.fake.fake'),/سیستم دیگری/);
  process.env.BILITFAST_HOST_MACHINE_ID_FILE = path.join(tmp,'missing');
  assert.throws(()=>license.status(),/ENOENT/);
  process.env.BILITFAST_HOST_MACHINE_ID_FILE = sourceA;
  assert.equal(license.initial().instanceId,record.instanceId);
  assert.equal(license.status().state,'active');
  console.log('PASS: copied installation refuses mismatched or missing host identity and works on original host');
  const legacyDir = path.join(tmp,'legacy');
  fs.mkdirSync(legacyDir);
  process.env.BILITFAST_DATA_DIR = legacyDir;
  const legacy = {v:1,instanceId:'c'.repeat(32),installedAt:new Date().toISOString(),lastSeen:Date.now(),license:null};
  fs.writeFileSync(path.join(legacyDir,'installation.json'), JSON.stringify(legacy));
  assert.throws(()=>license.status(),/مهاجرت کنترل‌شده/);
  assert.throws(()=>license.migrateLegacy(),/تایید صریح/);
  process.env.BILITFAST_MIGRATE_LEGACY_INSTALLATION='1';
  const crypto=require('node:crypto');
  const {privateKey,publicKey}=crypto.generateKeyPairSync('ed25519');
  const publicFile=path.join(tmp,'migration-public.pem');
  fs.writeFileSync(publicFile,publicKey.export({format:'pem',type:'spki'}));
  process.env.BILITFAST_VENDOR_PUBLIC_KEY_PATH=publicFile;
  const {createMigrationCode}=require('../lib/vendor-license');
  const hostHash=require('../lib/host-machine').machineIdentity();
  const sign=(id,host)=>createMigrationCode(privateKey.export({format:'pem',type:'pkcs8'}),id,host).code;
  assert.throws(()=>license.migrateLegacy('BFM1.forged.forged'),/مجوز مهاجرت فروشنده/);
  assert.throws(()=>license.migrateLegacy(sign(legacy.instanceId,'b'.repeat(64))),/مجوز مهاجرت فروشنده/);
  assert.throws(()=>license.migrateLegacy(sign('a'.repeat(32),hostHash)),/مجوز مهاجرت فروشنده/);
  assert.equal(JSON.parse(fs.readFileSync(path.join(legacyDir,'installation.json'))).v,1);
  const moved = license.migrateLegacy(sign(legacy.instanceId,hostHash));
  assert(fs.existsSync(moved.backup));
  assert.equal(license.read().v,2);
  assert.equal(license.read().instanceId,legacy.instanceId);
  assert.equal(license.status().state,'active');
  console.log('PASS: v1 migration requires signed seller approval for the precise installation+host, with backup');
} finally {
  for(const k of Object.keys(process.env)) if (!(k in before)) delete process.env[k];
  for(const [k,v] of Object.entries(before)) process.env[k]=v;
  fs.rmSync(tmp,{recursive:true,force:true});
}
