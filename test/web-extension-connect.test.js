'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const origin=require('../extension/target-origin');
const direct=require('../extension/direct-session');
const manifest=require('../extension/manifest.json');
assert.equal(manifest.version, require('../package.json').version);
assert(manifest.permissions.includes('tabs')&&manifest.permissions.includes('cookies'));
assert(manifest.host_permissions.includes('https://safirrail.ir/*'));
for(const value of ['https://evil.example','http://safirrail.ir/etrain','https://sub.safirrail.ir/etrain'])
 assert(!direct.official(value));
assert(direct.official('https://safirrail.ir/etrain/index.php'));
assert(origin.fromTab({url:'http://127.0.0.1:3000/login.html'}).localPreview);
assert.throws(()=>origin.fromTab({url:'http://127.0.0.1:3210/login.html'}));
const popup=fs.readFileSync(path.join(__dirname,'../extension/popup.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../extension/popup.html'),'utf8');
assert(popup.includes('BilitCookieReader.collect(chrome)'));
assert(popup.includes("world:'MAIN'"));
assert(!popup.includes('chrome.storage.local.set'));
assert(!popup.includes("action:'push'"));
assert(!html.includes('id="code"')&&!html.includes('id="start-booking"'));
console.log('ALL direct extension wiring checks passed');
