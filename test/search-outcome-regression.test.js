/* Ensures ordinary no-capacity responses never trigger exponential backoff. */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const c = require('../public/search-outcome');
const expect = (response, classification) => assert.equal(c.classify(response), classification, JSON.stringify(response));
expect({ok:true,trains:[]}, 'no_capacity');
expect({ok:true,trains:[],availabilityStatus:'no_match'}, 'no_match');
expect({ok:true,trains:[],availabilityStatus:'availability_unverified'}, 'availability_unverified');
expect({ok:true,trains:[],note:'موجودی صفر'}, 'no_capacity');
expect({ok:false,noCapacity:true,error:'ظرفیت تکمیل'}, 'no_capacity');
expect({ok:false,reason:'no_capacity'}, 'no_capacity');
expect({ok:false,code:'NO_CAPACITY'}, 'no_capacity');
expect({ok:true,trains:[{train_number:'123'}]}, 'found');
expect({ok:false,captchaRequired:true}, 'captcha_required');
expect({ok:false,captchaInvalid:true}, 'captcha_required');
expect({ok:false,sessionInvalid:true}, 'session_required');
expect({ok:false,loginRequired:true}, 'session_required');
expect({ok:false,reason:'invalid_input',fatal:true}, 'blocked');
expect({ok:false,httpStatus:402,licenseRequired:true}, 'blocked');
expect({ok:false,httpStatus:429}, 'transport_error');
expect({ok:false,httpStatus:503}, 'transport_error');
expect({ok:false,netError:true}, 'transport_error');
expect({ok:false,netError:true,httpStatus:400}, 'transport_error');
expect({ok:false,transient:true,httpStatus:400}, 'transport_error');
expect({ok:false,transient:true}, 'transport_error');
expect({ok:false,httpStatus:400,error:'invalid input'}, 'blocked');
expect({ok:false,httpStatus:429,transient:true}, 'transport_error');
expect({ok:false,httpStatus:401,sessionInvalid:true}, 'session_required');
expect({ok:false,httpStatus:400,quotaExceeded:true,netError:true}, 'blocked');
expect({ok:false,error:'unknown downstream response'}, 'unexpected');
expect({ok:true}, 'unexpected');
expect(null, 'unexpected');
const html = fs.readFileSync(path.join(__dirname,'../public/route.html'),'utf8');
assert.match(html, /const outcome = BilitSearchOutcome\.classify\(data\)/);
assert.match(html, /if \(outcome === 'transport_error'\) \{\s*consecFails\+\+/);
assert.match(html, /if \(outcome === 'captcha_required'\)/);
assert.match(html, /outcome === 'no_capacity'/);
assert.match(html, /outcome === 'no_match'/);
assert.match(html, /outcome === 'availability_unverified'/);
assert.match(html, /noteSuccess\(\);/);
assert.match(html, /if \(outcome === 'found'\) markHot\(\)/);
assert.match(html, /scheduleNextPoll\(\);/);
const sw = fs.readFileSync(path.join(__dirname,'../public/sw.js'),'utf8');
assert.match(sw, /search-outcome\.js/);
assert(!html.includes('if (!data.ok) {\n      // خطای واقعاً دائمی'));
const core = fs.readFileSync(path.join(__dirname,'../lib/core.js'),'utf8');
assert.match(core, /AbortError[\s\S]*?transient: true, netError: true/);
assert.match(core, /httpStatus: resp\.status/);
console.log('PASS: search result / backoff regression checks');
